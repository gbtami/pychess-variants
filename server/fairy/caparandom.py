def caparandom_rank8_from_id(position_id: int) -> str:
    """Return the back rank for a canonical Scharnagl CRC position ID."""
    if not 1 <= position_id <= _CAPARANDOM_POSITION_COUNT:
        raise ValueError("Capablanca Random position ID must be in 1..48000")

    # Scharnagl's scheme uses 48000 for the all-zero mixed-radix value.
    value = position_id % _CAPARANDOM_POSITION_COUNT
    qa_swapped = value % 2
    value //= 2
    qa_bright = value % 5
    value //= 5
    qa_dark = value % 5
    value //= 5
    bishop_bright = value % 4
    value //= 4
    bishop_dark = value % 4
    value //= 4
    chancellor = value % 6
    value //= 6
    knight_pair = value % 10

    rank8 = [""] * 10
    bright_piece, dark_piece = ("q", "a") if qa_swapped else ("a", "q")
    rank8[_BRIGHT_SQUARES[qa_bright]] = bright_piece
    rank8[_DARK_SQUARES[qa_dark]] = dark_piece

    free_bright = [pos for pos in _BRIGHT_SQUARES if not rank8[pos]]
    rank8[free_bright[bishop_bright]] = "b"

    free_dark = [pos for pos in _DARK_SQUARES if not rank8[pos]]
    rank8[free_dark[bishop_dark]] = "b"

    free = [pos for pos in range(10) if not rank8[pos]]
    rank8[free[chancellor]] = "c"

    free = [pos for pos in range(10) if not rank8[pos]]
    knight_left, knight_right = _KNIGHT_PAIRS[knight_pair]
    rank8[free[knight_left]] = "n"
    rank8[free[knight_right]] = "n"

    free = [pos for pos in range(10) if not rank8[pos]]
    rank8[free[0]] = "r"
    rank8[free[1]] = "k"
    rank8[free[2]] = "r"

    return "".join(rank8)


def caparandom_id_from_rank8(rank8: str) -> int:
    """Return the canonical Scharnagl CRC ID for a 10-piece back rank."""
    rank8 = rank8.lower()
    if len(rank8) != 10 or sorted(rank8) != sorted("abbcknnqrr"):
        raise ValueError("Invalid Capablanca Random back rank")

    bright_qa = [pos for pos in _BRIGHT_SQUARES if rank8[pos] in "qa"]
    dark_qa = [pos for pos in _DARK_SQUARES if rank8[pos] in "qa"]
    if len(bright_qa) != 1 or len(dark_qa) != 1:
        raise ValueError("Queen and archbishop must be on opposite colors")

    qa_bright_pos = bright_qa[0]
    qa_dark_pos = dark_qa[0]
    if {rank8[qa_bright_pos], rank8[qa_dark_pos]} != {"q", "a"}:
        raise ValueError("Queen and archbishop must be on opposite colors")

    qa_swapped = int(rank8[qa_bright_pos] == "q")
    qa_bright = _BRIGHT_SQUARES.index(qa_bright_pos)
    qa_dark = _DARK_SQUARES.index(qa_dark_pos)

    free_bright = [pos for pos in _BRIGHT_SQUARES if pos != qa_bright_pos]
    bright_bishops = [pos for pos in free_bright if rank8[pos] == "b"]
    free_dark = [pos for pos in _DARK_SQUARES if pos != qa_dark_pos]
    dark_bishops = [pos for pos in free_dark if rank8[pos] == "b"]
    if len(bright_bishops) != 1 or len(dark_bishops) != 1:
        raise ValueError("Bishops must be on opposite colors")

    bright_bishop_pos = bright_bishops[0]
    dark_bishop_pos = dark_bishops[0]
    bishop_bright = free_bright.index(bright_bishop_pos)
    bishop_dark = free_dark.index(dark_bishop_pos)

    occupied = {qa_bright_pos, qa_dark_pos, bright_bishop_pos, dark_bishop_pos}
    free = [pos for pos in range(10) if pos not in occupied]
    chancellor_pos = rank8.index("c")
    if chancellor_pos not in free:
        raise ValueError("Invalid Capablanca Random back rank")
    chancellor = free.index(chancellor_pos)
    occupied.add(chancellor_pos)

    free = [pos for pos in range(10) if pos not in occupied]
    knight_pair_positions = tuple(i for i, pos in enumerate(free) if rank8[pos] == "n")
    try:
        knight_pair = _KNIGHT_PAIRS.index(knight_pair_positions)
    except ValueError as exc:
        raise ValueError("Invalid Capablanca Random back rank") from exc

    occupied.update(pos for pos in free if rank8[pos] == "n")
    free = [pos for pos in range(10) if pos not in occupied]
    if "".join(rank8[pos] for pos in free) != "rkr":
        raise ValueError("King must be between the rooks")

    value = knight_pair
    value = value * 6 + chancellor
    value = value * 4 + bishop_dark
    value = value * 4 + bishop_bright
    value = value * 5 + qa_dark
    value = value * 5 + qa_bright
    value = value * 2 + qa_swapped

    return _CAPARANDOM_POSITION_COUNT if value == 0 else value


def caparandom_rank8() -> str:
    position_id = random.choice(CAPARANDOM_VALID_IDS)
    return caparandom_rank8_from_id(position_id)
